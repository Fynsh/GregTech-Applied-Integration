package com.Fynsh.gtai.block;

/**
 * 矩阵方块在结构中的角色。
 *
 * <p>角色是成型判定唯一依赖的分类：外壳、内部、主方块等。具体等级/类型/处理类型
 * 放在 {@link MatrixBlockKind} 里，避免在扫描代码中反复解析注册名字符串。</p>
 */
public enum MatrixBlockRole {

    /** 矩阵框架（普通或超净）。可在外壳任何位置，8 个顶点只允许它。 */
    FRAME,

    /** 矩阵玻璃（普通或超净）。只允许在普通表面，不允许在棱或顶点。 */
    GLASS,

    /** 矩阵样板核心（普通或扩展）。只允许在内部。 */
    PATTERN_CORE,

    /** 矩阵处理核心（普通或扩展）。只允许在内部。 */
    PROCESSING_CORE,

    /** 矩阵速度核心（普通或扩展）。只允许在内部。 */
    SPEED_CORE,

    /** 矩阵监控器核心（普通或扩展）。只允许在内部，且整个结构有且仅有一个。 */
    MONITOR,

    /** 集成变压器。只允许在内部，不参与类型/等级匹配。 */
    TRANSFORMER,

    /** 集成有源变压器。只允许在内部，不参与类型/等级匹配。 */
    ACTIVE_TRANSFORMER,

    /** 集成超净间。只允许在内部，且最多一个。 */
    CLEANROOM,

    /** 过滤器机械方块。只允许在普通表面。 */
    FILTER,

    /** 无菌过滤器机械方块。成型判定与普通过滤器完全相同。 */
    STERILE_FILTER,

    /** 空应用集成矩阵核心。只允许在内部，是真实方块而非空气。 */
    EMPTY_CORE
}
